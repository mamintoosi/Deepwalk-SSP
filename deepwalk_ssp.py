    cleaned_str = embeddings_str.replace('\n', ', ').replace('[', '').replace(']', '')
    embeddings_list = np.array([[float(num) for num in row.split()] for row in cleaned_str.split(',') if row])
    embeddings = np.array(embeddings_list)

