def cluster_students_and_evaluate(data):
    results = {}

    # KMeans
    kmeans = KMeans(n_clusters=2, n_init=10, random_state=42).fit(data)
    results['kmeans_labels'] = kmeans.labels_
    results['kmeans_silhouette'] = silhouette_score(data, kmeans.labels_)
    results['kmeans_davies_bouldin'] = davies_bouldin_score(data, kmeans.labels_)
    results['kmeans_calinski_harabasz'] = calinski_harabasz_score(data, kmeans.labels_)

    # Affinity Propagation
    affinity = AffinityPropagation().fit(data)
    results['affinity_labels'] = affinity.labels_
    results['affinity_silhouette'] = silhouette_score(data, affinity.labels_)
    results['affinity_davies_bouldin'] = davies_bouldin_score(data, affinity.labels_)
    results['affinity_calinski_harabasz'] = calinski_harabasz_score(data, affinity.labels_)

    # Gaussian Mixture Model
    gmm = GaussianMixture(n_components=2, random_state=42).fit(data)
    gmm_labels = gmm.predict(data)
    results['gmm_labels'] = gmm_labels
    results['gmm_silhouette'] = silhouette_score(data, gmm_labels)
    results['gmm_davies_bouldin'] = davies_bouldin_score(data, gmm_labels)
    results['gmm_calinski_harabasz'] = calinski_harabasz_score(data, gmm_labels)

    # Agglomerative Clustering
    agglomerative = AgglomerativeClustering(n_clusters=2).fit(data)
    results['agglomerative_labels'] = agglomerative.labels_
    results['agglomerative_silhouette'] = silhouette_score(data, agglomerative.labels_)
    results['agglomerative_davies_bouldin'] = davies_bouldin_score(data, agglomerative.labels_)
    results['agglomerative_calinski_harabasz'] = calinski_harabasz_score(data, agglomerative.labels_)

    return results

